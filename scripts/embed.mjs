// Bundles web/*.html (with web/theme.js and web/diagram.js inlined) into src/generated/pages.ts so the server needs no file reads.
import { readFileSync, writeFileSync } from 'node:fs';
import { inlineScripts } from '../src/shared.js';

const names = ['index', 'login', 'viewer', 'privacy', 'terms'];
const root = new URL('..', import.meta.url);
const scripts = { theme: readFileSync(new URL('web/theme.js', root), 'utf8'), diagram: readFileSync(new URL('web/diagram.js', root), 'utf8') };
const body = names.map(n => `  ${n}: ${JSON.stringify(inlineScripts(readFileSync(new URL(`web/${n}.html`, root), 'utf8'), scripts))},`).join('\n');
writeFileSync(new URL('src/generated/pages.ts', root), `// Generated by scripts/embed.mjs from web/*.html. Do not edit.\nexport const pages = {\n${body}\n};\n`);
