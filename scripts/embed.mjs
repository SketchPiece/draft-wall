// Bundles web/*.html into src/generated/pages.ts so the Vercel function needs no file reads.
import { readFileSync, writeFileSync } from 'node:fs';

const names = ['index', 'login', 'viewer', 'privacy', 'terms'];
const root = new URL('..', import.meta.url);
const body = names.map(n => `  ${n}: ${JSON.stringify(readFileSync(new URL(`web/${n}.html`, root), 'utf8'))},`).join('\n');
writeFileSync(new URL('src/generated/pages.ts', root), `// Generated by scripts/embed.mjs from web/*.html. Do not edit.\nexport const pages = {\n${body}\n};\n`);
